function plPlural(n, one, few, many) {
  return n === 1 ? one : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? few : many;
}

export function pickLang(wanted) {
  const list = wanted && wanted !== "auto" ? [wanted] : navigator.languages || [navigator.language];
  for (const l of list) {
    const base = String(l).toLowerCase().split("-")[0];
    if (STRINGS[base]) return base;
  }
  return "en";
}
